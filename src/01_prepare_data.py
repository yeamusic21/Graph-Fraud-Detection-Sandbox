"""
01_prepare_data.py

Prepare the simulated workers' compensation data for analysis and graph loading.

INPUT
-----
The raw CSV files generated by 00_simulate_data.py:

    data/raw/claimants.csv
    data/raw/employers.csv
    data/raw/providers.csv
    data/raw/treatments.csv
    data/raw/claims.csv
    data/raw/provider_referrals.csv

PROCESS
-------
1. Load the raw CSV files.
2. Validate the expected columns.
3. Normalize identifiers and data types.
4. Check for duplicate records and missing values.
5. Validate relationships between entities.
6. Check claim amounts and fraud labels.
7. Create an enriched, claim-level dataset for analysis.
8. Save the prepared datasets and a data quality report.

OUTPUT
------
Prepared CSV files:

    data/processed/claimants.csv
    data/processed/employers.csv
    data/processed/providers.csv
    data/processed/treatments.csv
    data/processed/claims.csv
    data/processed/provider_referrals.csv
    data/processed/claims_enriched.csv
    data/processed/data_quality_report.json

DESIGN PRINCIPLES
-----------------
- Keep the code straightforward and easy to follow.
- Do not perform fraud detection in this script.
- Do not connect to Neo4j in this script.
- Preserve fraud labels so they can be used later for evaluation.
- Fail early when data integrity problems would make downstream
  analysis unreliable.

The simulated provider ring already exists in the raw data.
This script prepares that data; it does not inject additional fraud.
"""

