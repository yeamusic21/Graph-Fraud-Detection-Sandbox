# 5. Generate a data quality report
# =============================================================

def create_quality_report(data):
    """
    Summarize dataset sizes, missing values, and fraud labels.

    The report is intended to help us verify that the simulator
    generated the expected data before beginning analysis.
    """

    report = {
        "datasets": {},
        "summary": {},
    }

    # ---------------------------------------------------------
    # Dataset-level statistics
    # ---------------------------------------------------------

    for dataset_name, df in data.items():

        dataset_report = {
            "row_count": int(len(df)),
            "column_count": int(len(df.columns)),
            "columns": list(df.columns),
            "missing_values": {
                column: int(count)
                for column, count in (
                    df.isna().sum().items()
                )
                if count > 0
            },
        }

        report["datasets"][dataset_name] = (
            dataset_report
        )

    # ---------------------------------------------------------
    # Claim-level statistics
    # ---------------------------------------------------------

    claims = data["claims"]

    report["summary"]["total_claims"] = int(
        len(claims)
    )

    report["summary"]["total_claim_amount"] = float(
        claims["claim_amount"].sum()
    )

    report["summary"]["average_claim_amount"] = (
        float(claims["claim_amount"].mean())
        if len(claims) > 0
        else None
    )

    # ---------------------------------------------------------
    # Claim fraud statistics
    # ---------------------------------------------------------

    claim_fraud_count = int(
        claims["is_fraud"].sum()
    )

    report["summary"]["fraudulent_claims"] = (
        claim_fraud_count
    )

    report["summary"]["claim_fraud_rate"] = (
        float(claims["is_fraud"].mean())
        if len(claims) > 0
        else None
    )

    # ---------------------------------------------------------
    # Provider fraud statistics
    # ---------------------------------------------------------

    providers = data["providers"]

    provider_fraud_count = int(
        providers["is_fraud"].sum()
    )

    report["summary"]["total_providers"] = int(
        len(providers)
    )

    report["summary"]["flagged_providers"] = (
        provider_fraud_count
    )

    report["summary"]["provider_fraud_rate"] = (
        float(providers["is_fraud"].mean())
        if len(providers) > 0
        else None
    )

    return report


