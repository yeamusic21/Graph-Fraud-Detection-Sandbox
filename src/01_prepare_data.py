# These are the columns required for each dataset.
#
# Additional columns are allowed. We only require that these
# columns exist, so the preparation script remains compatible
# with future extensions to the simulation.

REQUIRED_COLUMNS = {
    "claimants": [
        "claimant_id",
    ],
    "employers": [
        "employer_id",
    ],
    "providers": [
        "provider_id",
        "is_fraud",
    ],
    "treatments": [
        "treatment_id",
        "treatment_type",
    ],
    "claims": [
        "claim_id",
        "claimant_id",
        "employer_id",
        "provider_id",
        "treatment_id",
        "claim_amount",
        "is_fraud",
    ],
    "provider_referrals": [
        "provider_id",
        "referred_provider_id",
    ],
}


# Each dataset has a primary key that should uniquely identify
# every record.

PRIMARY_KEYS = {
    "claimants": "claimant_id",
    "employers": "employer_id",
    "providers": "provider_id",
    "treatments": "treatment_id",
    "claims": "claim_id",
}


# Columns that represent identifiers.
#
# Treat identifiers as strings rather than numbers.
#
# For example, claimant IDs are labels, not quantities.
# We should never calculate an average claimant ID.

IDENTIFIER_COLUMNS = {
    "claimants": [
        "claimant_id",
    ],
    "employers": [
        "employer_id",
    ],
    "providers": [
        "provider_id",
    ],
    "treatments": [
        "treatment_id",
    ],
    "claims": [
        "claim_id",
        "claimant_id",
        "employer_id",
        "provider_id",
        "treatment_id",
    ],
    "provider_referrals": [
        "provider_id",
        "referred_provider_id",
    ],
}


