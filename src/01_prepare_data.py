# 6. Main preparation pipeline
# =============================================================

def main():
    """
    Run the complete data preparation pipeline.
    """

    print("\n" + "=" * 65)
    print("WORKERS' COMPENSATION FRAUD DETECTION")
    print("STEP 1: PREPARE DATA")
    print("=" * 65)

    # ---------------------------------------------------------
    # Step 1: Verify the raw data directory
    # ---------------------------------------------------------

    if not RAW_DATA_DIR.exists():
        raise FileNotFoundError(
            f"Raw data directory does not exist: "
            f"{RAW_DATA_DIR}\n"
            "Run src/00_simulate_data.py first."
        )

    # Create the processed directory if it does not exist.
    PROCESSED_DATA_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # ---------------------------------------------------------
    # Step 2: Load all raw datasets
    # ---------------------------------------------------------

    print("\n[1/7] Loading raw datasets...")

    data = {}

    for dataset_name in REQUIRED_COLUMNS:

        data[dataset_name] = load_csv(
            dataset_name
        )

    # ---------------------------------------------------------
    # Step 3: Normalize identifiers and validate records
    # ---------------------------------------------------------

    print("\n[2/7] Normalizing identifiers...")

    for dataset_name, df in data.items():

        data[dataset_name] = normalize_identifiers(
            dataset_name,
            df,
        )

    print("\n[3/7] Checking required values and primary keys...")

    for dataset_name, df in data.items():

        # Check that required fields are populated.
        check_required_values(
            dataset_name,
            df,
        )

        # Entity and claim tables must have unique primary keys.
        #
        # Referral records do not have a primary key defined
        # by this schema. They are checked separately below.

        if dataset_name in PRIMARY_KEYS:

            check_primary_key(
                dataset_name,
                df,
            )

    # ---------------------------------------------------------
    # Step 4: Normalize fraud labels and claim amounts
    # ---------------------------------------------------------

    print("\n[4/7] Validating data types...")

    data["providers"] = normalize_boolean_column(
        data["providers"],
        "is_fraud",
        "providers",
    )

    data["claims"] = normalize_boolean_column(
        data["claims"],
        "is_fraud",
        "claims",
    )

    data["claims"] = prepare_claim_amounts(
        data["claims"]
    )

    # ---------------------------------------------------------
    # Step 5: Validate entity relationships
    # ---------------------------------------------------------

    print("\n[5/7] Validating entity relationships...")

    check_foreign_keys(data)

    # ---------------------------------------------------------
    # Step 6: Create the enriched claims dataset
    # ---------------------------------------------------------

    print("\n[6/7] Creating enriched claims dataset...")

    claims_enriched = create_claims_enriched(
        data
    )

    # ---------------------------------------------------------
    # Step 7: Save processed datasets and report
    # ---------------------------------------------------------

    print("\n[7/7] Saving processed datasets...")

    # Save the prepared versions of the original datasets.
    #
    # We retain the original entity relationships and fraud
    # labels so that the data can be loaded into Neo4j later.

    for dataset_name, df in data.items():

        output_path = (
            PROCESSED_DATA_DIR
            / f"{dataset_name}.csv"
        )

        df.to_csv(
            output_path,
            index=False,
        )

        print(f"Saved: {output_path.name}")

    # Save the additional claim-level dataset.
    enriched_path = (
        PROCESSED_DATA_DIR
        / "claims_enriched.csv"
    )

    claims_enriched.to_csv(
        enriched_path,
        index=False,
    )

    print(
        f"Saved: {enriched_path.name}"
    )

    # Create a report summarizing the prepared data.
    report = create_quality_report(
        data
    )

    report_path = (
        PROCESSED_DATA_DIR
        / "data_quality_report.json"
    )

    with open(
        report_path,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            report,
            file,
            indent=4,
        )

    print(
        f"Saved: {report_path.name}"
    )

    # ---------------------------------------------------------
    # Print a final summary
    # ---------------------------------------------------------

    print("\n" + "=" * 65)
    print("DATA PREPARATION COMPLETE")
    print("=" * 65)

    print(
        f"Claimants:          "
        f"{len(data['claimants']):,}"
    )

    print(
        f"Employers:          "
        f"{len(data['employers']):,}"
    )

    print(
        f"Providers:          "
        f"{len(data['providers']):,}"
    )

    print(
        f"Treatments:         "
        f"{len(data['treatments']):,}"
    )

    print(
        f"Claims:             "
        f"{len(data['claims']):,}"
    )

    print(
        f"Provider referrals: "
        f"{len(data['provider_referrals']):,}"
    )

    print(
        f"Fraudulent claims:  "
        f"{int(data['claims']['is_fraud'].sum()):,}"
    )

    print(
        f"Flagged providers:  "
        f"{int(data['providers']['is_fraud'].sum()):,}"
    )

    print(
        f"\nProcessed files are located in:\n"
        f"{PROCESSED_DATA_DIR}"
    )

    print("\nNext step: src/02_baseline_analysis.py")


# =============================================================
# 7. Execute the pipeline
# =============================================================

if __name__ == "__main__":
    main()