# 3. Helper functions
# =============================================================

def load_csv(dataset_name):
    """
    Load one raw CSV file and validate its required columns.

    Parameters
    ----------
    dataset_name : str
        Dataset name without the .csv extension.

    Returns
    -------
    pandas.DataFrame
        The loaded dataset.

    Raises
    ------
    FileNotFoundError
        If the expected CSV does not exist.

    ValueError
        If required columns are missing.
    """

    # Construct the input filename.
    file_path = RAW_DATA_DIR / f"{dataset_name}.csv"

    # Fail early if the simulator has not generated the file.
    if not file_path.exists():
        raise FileNotFoundError(
            f"Required input file was not found: {file_path}\n"
            "Run src/00_simulate_data.py first."
        )

    # Read every CSV field initially as a string.
    #
    # This prevents identifiers from being interpreted as
    # numbers and losing formatting such as leading zeros.
    #
    # Numeric columns will be converted explicitly later.

    df = pd.read_csv(
        file_path,
        dtype=str,
    )

    # Check that all required columns exist.
    missing_columns = [
        column
        for column in REQUIRED_COLUMNS[dataset_name]
        if column not in df.columns
    ]

    if missing_columns:
        raise ValueError(
            f"Dataset '{dataset_name}' is missing required "
            f"columns: {missing_columns}"
        )

    print(
        f"Loaded {dataset_name}.csv: "
        f"{len(df):,} rows"
    )

    return df


def normalize_identifiers(dataset_name, df):
    """
    Normalize identifier columns.

    Identifiers are stored as strings, with surrounding
    whitespace removed.

    Empty identifiers are converted to missing values so that
    they can be detected during validation.
    """

    for column in IDENTIFIER_COLUMNS[dataset_name]:

        # Convert values to strings while preserving missing
        # values as missing rather than converting them to "nan".
        #
        # Because load_csv reads the CSV as strings, identifiers
        # should normally already be strings.

        df[column] = df[column].str.strip()

        # Treat empty strings as missing identifiers.
        df[column] = df[column].replace("", pd.NA)

    return df


def normalize_boolean_column(df, column, dataset_name):
    """
    Convert a fraud-label column to pandas' nullable Boolean type.

    Accepted representations include:
        True / False
        true / false
        1 / 0
        yes / no

    Missing or unrecognized values cause an error.

    We deliberately do not guess what an unknown fraud label
    means because these labels are important for evaluation.
    """

    # Map common textual representations to actual booleans.
    boolean_mapping = {
        "true": True,
        "false": False,
        "1": True,
        "0": False,
        "yes": True,
        "no": False,
    }

    # Standardize text before applying the mapping.
    normalized = (
        df[column]
        .astype("string")
        .str.strip()
        .str.lower()
    )

    # Replace known representations with booleans.
    converted = normalized.map(boolean_mapping)

    # Missing and invalid values should not silently become False.
    invalid_mask = converted.isna()

    if invalid_mask.any():
        invalid_values = (
            normalized[invalid_mask]
            .unique()
            .tolist()
        )

        raise ValueError(
            f"Invalid or missing fraud labels in "
            f"{dataset_name}.{column}: {invalid_values}"
        )

    # Use a proper Boolean dtype.
    df[column] = converted.astype(bool)

    return df


def check_primary_key(dataset_name, df):
    """
    Check that the primary key exists and is unique.

    Duplicate entity IDs can cause incorrect joins and
    duplicate nodes when the data is loaded into Neo4j.
    """

    primary_key = PRIMARY_KEYS[dataset_name]

    # A primary key must never be missing.
    if df[primary_key].isna().any():

        missing_count = int(
            df[primary_key].isna().sum()
        )

        raise ValueError(
            f"{dataset_name}.csv contains "
            f"{missing_count} missing {primary_key} values."
        )

    # Identify duplicate IDs.
    duplicate_mask = df[primary_key].duplicated(
        keep=False
    )

    if duplicate_mask.any():

        duplicate_ids = (
            df.loc[duplicate_mask, primary_key]
            .unique()
            .tolist()
        )

        raise ValueError(
            f"{dataset_name}.csv contains duplicate "
            f"{primary_key} values: {duplicate_ids[:10]}"
        )


def check_required_values(dataset_name, df):
    """
    Check for missing values in required columns.

    We fail rather than silently deleting records.

    Silently dropping a claim, provider, or claimant could
    distort our simulated recovery paths and fraud labels.
    """

    required_columns = REQUIRED_COLUMNS[dataset_name]

    missing_counts = (
        df[required_columns]
        .isna()
        .sum()
    )

    missing_counts = missing_counts[
        missing_counts > 0
    ]

    if not missing_counts.empty:

        details = missing_counts.to_dict()

        raise ValueError(
            f"Missing required values in "
            f"{dataset_name}.csv: {details}"
        )


def check_foreign_keys(data):
    """
    Validate relationships between datasets.

    For example, every claim should reference an existing
    claimant, employer, provider, and treatment.

    These checks are important because downstream graph
    analysis depends on valid relationships.
    """

    claims = data["claims"]

    # ---------------------------------------------------------
    # Claims -> Claimants
    # ---------------------------------------------------------

    valid_claimants = set(
        data["claimants"]["claimant_id"]
    )

    invalid_claimants = set(
        claims["claimant_id"]
    ) - valid_claimants

    if invalid_claimants:
        raise ValueError(
            "Claims reference unknown claimants: "
            f"{list(invalid_claimants)[:10]}"
        )

    # ---------------------------------------------------------
    # Claims -> Employers
    # ---------------------------------------------------------

    valid_employers = set(
        data["employers"]["employer_id"]
    )

    invalid_employers = set(
        claims["employer_id"]
    ) - valid_employers

    if invalid_employers:
        raise ValueError(
            "Claims reference unknown employers: "
            f"{list(invalid_employers)[:10]}"
        )

    # ---------------------------------------------------------
    # Claims -> Providers
    # ---------------------------------------------------------

    valid_providers = set(
        data["providers"]["provider_id"]
    )

    invalid_providers = set(
        claims["provider_id"]
    ) - valid_providers

    if invalid_providers:
        raise ValueError(
            "Claims reference unknown providers: "
            f"{list(invalid_providers)[:10]}"
        )

    # ---------------------------------------------------------
    # Claims -> Treatments
    # ---------------------------------------------------------

    valid_treatments = set(
        data["treatments"]["treatment_id"]
    )

    invalid_treatments = set(
        claims["treatment_id"]
    ) - valid_treatments

    if invalid_treatments:
        raise ValueError(
            "Claims reference unknown treatments: "
            f"{list(invalid_treatments)[:10]}"
        )

    # ---------------------------------------------------------
    # Provider referrals -> Providers
    # ---------------------------------------------------------

    referrals = data["provider_referrals"]

    invalid_referral_sources = (
        set(referrals["provider_id"])
        - valid_providers
    )

    if invalid_referral_sources:
        raise ValueError(
            "Provider referrals reference unknown "
            "source providers: "
            f"{list(invalid_referral_sources)[:10]}"
        )

    invalid_referral_targets = (
        set(referrals["referred_provider_id"])
        - valid_providers
    )

    if invalid_referral_targets:
        raise ValueError(
            "Provider referrals reference unknown "
            "destination providers: "
            f"{list(invalid_referral_targets)[:10]}"
        )

    print("Foreign-key validation passed.")


def prepare_claim_amounts(claims):
    """
    Convert claim_amount to a numeric column.

    Claim amounts must be numeric, present, and nonnegative.

    We do not remove unusually large claims here. An unusually
    large amount could be legitimate, and removing it could
    eliminate important information from later analysis.
    """

    claims["claim_amount"] = pd.to_numeric(
        claims["claim_amount"],
        errors="coerce",
    )

    # Reject missing or nonnumeric amounts.
    if claims["claim_amount"].isna().any():

        invalid_count = int(
            claims["claim_amount"].isna().sum()
        )

        raise ValueError(
            f"Found {invalid_count} missing or nonnumeric "
            "claim_amount values."
        )

    # Reject negative amounts.
    if (claims["claim_amount"] < 0).any():
        raise ValueError(
            "Found negative claim_amount values."
        )

    # Reject infinite values.
    if not claims["claim_amount"].map(
        lambda value: pd.notna(value)
        and abs(value) != float("inf")
    ).all():

        raise ValueError(
            "Found infinite claim_amount values."
        )

    return claims


