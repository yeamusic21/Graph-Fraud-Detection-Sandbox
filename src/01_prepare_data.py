# 4. Create an enriched claim-level dataset
# =============================================================

def create_claims_enriched(data):
    """
    Join claims with provider fraud labels.

    The resulting dataset contains one row per claim and
    includes both:

        is_fraud
            The claim-level fraud label.

        provider_is_fraud
            The provider-level fraud label.

    Keeping these labels separate allows us to distinguish
    a fraudulent claim from a claim associated with a
    flagged provider.

    This function does not use fraud labels to make predictions.
    The labels are retained as ground truth for later evaluation.
    """

    claims = data["claims"].copy()

    providers = data["providers"].copy()

    # Rename the provider label before joining.
    #
    # Both datasets have an is_fraud column, so explicitly
    # naming the provider label prevents ambiguity.

    providers = providers.rename(
        columns={
            "is_fraud": "provider_is_fraud"
        }
    )

    # We only need the provider ID and its fraud label here.
    providers = providers[
        [
            "provider_id",
            "provider_is_fraud",
        ]
    ]

    # Join each claim to its provider's fraud label.
    #
    # validate="many_to_one" ensures that multiple claims can
    # belong to the same provider, but each provider ID must
    # match no more than one provider record.

    claims_enriched = claims.merge(
        providers,
        on="provider_id",
        how="left",
        validate="many_to_one",
        indicator=True,
    )

    # Every claim should have matched a provider.
    unmatched = claims_enriched["_merge"] != "both"

    if unmatched.any():
        raise ValueError(
            "Some claims could not be matched to providers."
        )

    # The merge indicator is no longer needed.
    claims_enriched = claims_enriched.drop(
        columns=["_merge"]
    )

    # Put the most important identifiers first.
    #
    # Keep any additional columns generated by the simulator.

    preferred_columns = [
        "claim_id",
        "claimant_id",
        "employer_id",
        "provider_id",
        "treatment_id",
        "claim_amount",
        "is_fraud",
        "provider_is_fraud",
    ]

    ordered_columns = [
        column
        for column in preferred_columns
        if column in claims_enriched.columns
    ]

    remaining_columns = [
        column
        for column in claims_enriched.columns
        if column not in ordered_columns
    ]

    claims_enriched = claims_enriched[
        ordered_columns + remaining_columns
    ]

    return claims_enriched


